#!/usr/bin/env python3
"""Generates hier.S: stores that have to survive a cache hierarchy.

    python sw/tests/gen_hier.py          # rewrites sw/tests/hier.S
    python sw/tests/gen_hier.py <file>   # writes it somewhere else
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_wpolicy import Gen, LINE, SPAN  # noqa: E402

BASE = 0x4000               # check k uses 0x4000 + 0x100 * k (+ multiples of 4096)
AREA = 0x100                # bytes per check within one 4 KiB page: 8 lines


class Hier(Gen):
    def area(self):
        """Eight fresh neighbouring lines; with multiples of 4096 added they
        give as many lines as wanted in the same sets."""
        base = BASE + AREA * self.check
        assert base + AREA <= BASE + SPAN
        return base

    def read(self, addr):
        """A load whose value is not checked: it is there to take room."""
        self.emit(f"li   t4, {addr:#x}")
        self.emit("ld   t5, 0(t4)")


def generate():
    g = Hier()

    # Several dirty lines in one set, then more lines than any small set or
    # second level holds.
    a = g.area()
    g.begin("four dirty lines in one set, each with its own data, then four more lines")
    for k in range(4):
        g.store(a + SPAN * k + 8 * k, 8)
    for k in range(4, 8):
        g.read(a + SPAN * k)
    for k in range(4):
        g.expect(a + SPAN * k + 8 * k)
        g.expect(a + SPAN * k + 8 * ((k + 1) % 4))      # the rest of the line is zero

    a = g.area()
    g.begin("the same, read back in the opposite order")
    for k in range(4):
        g.store(a + SPAN * k, 8)
        g.store(a + SPAN * k + 24, 4)
    for k in range(4, 8):
        g.read(a + SPAN * k)
    for k in reversed(range(4)):
        g.expect(a + SPAN * k)
        g.expect(a + SPAN * k + 24)

    # Dirty lines in different sets of the first level that share a set of a
    # smaller second level.
    a = g.area()
    g.begin("dirty lines 64 bytes apart, then reads 64 bytes apart further on")
    for k in range(4):
        g.store(a + 2 * LINE * k + 16, 8)
    for k in range(4):
        g.read(a + SPAN + 2 * LINE * k)
        g.read(a + 2 * SPAN + 2 * LINE * k)
    for k in range(4):
        g.expect(a + 2 * LINE * k + 16)

    a = g.area()
    g.begin("stores to one line between reads that take room at both levels")
    for k in range(6):
        g.store(a + 8 * (k % 4), 8)
        g.read(a + SPAN * (k + 1))
        g.read(a + SPAN * (k + 1) + 2 * LINE)
    for k in range(4):
        g.expect(a + 8 * k)

    # A line that is stored to again right after it was pushed out: the new
    # store must land on the content that went down, not on a stale copy.
    a = g.area()
    g.begin("a line stored to, pushed out, stored to again in another place, pushed out again")
    for round_number in range(3):
        g.store(a + 8 * round_number, 8)
        for k in range(1, 6):
            g.read(a + SPAN * k)
    for k in range(4):
        g.expect(a + 8 * k)

    # Two dirty lines that keep pushing each other out, with a third and a
    # fourth joining: what a victim buffer catches and hands back.
    a = g.area()
    g.begin("two, then three, then four lines of one set stored to in turn")
    for count in (2, 3, 4):
        for round_number in range(3):
            for k in range(count):
                g.store(a + SPAN * k + 8 * (round_number % 4), 8)
    for k in range(4):
        for word in range(3):
            g.expect(a + SPAN * k + 8 * word)

    a = g.area()
    g.begin("five lines of one set read and stored to alternately")
    for round_number in range(3):
        for k in range(5):
            g.expect(a + SPAN * k + 8)
            g.store(a + SPAN * k + 8, 8)
    for k in range(5):
        g.expect(a + SPAN * k + 8)

    # A value kept in one line and updated in every step while other lines go
    # past: the hot line is the one a second level sees least of.
    a = g.area()
    g.begin("one line updated in every step while lines of its set go past")
    for step in range(12):
        g.store(a, 8)
        g.read(a + SPAN * (1 + step % 6))
        g.expect(a)
    g.expect(a + 8)

    a = g.area()
    g.begin("small stores to four lines of two sets, then room taken twice over")
    for k in range(4):
        g.store(a + LINE * (k % 2) + SPAN * (k // 2) + 3, 1)
        g.store(a + LINE * (k % 2) + SPAN * (k // 2) + 6, 2)
    for sweep in range(2):
        for k in range(2, 6):
            g.read(a + SPAN * k)
            g.read(a + SPAN * k + LINE)
    for k in range(4):
        g.expect(a + LINE * (k % 2) + SPAN * (k // 2))

    header = [
        "# hier.S - stores that have to survive a cache hierarchy.",
        "# GENERATED by sw/tests/gen_hier.py; do not edit by hand.",
        f"# Checks: {g.check}. Expected values are worked out by the generator.",
        ".equ HALT, 0x10000008",
    ]
    footer = [
        "",
        "pass:",
        "    li   t6, HALT",
        "    sd   x0, 0(t6)",
        "pass_loop:",
        "    j    pass_loop",
        "fail:",
        "    li   t6, HALT",
        "    sd   gp, 0(t6)",
        "fail_loop:",
        "    j    fail_loop",
        "",
    ]
    return "\n".join(header + g.out + footer)


if __name__ == "__main__":
    path = (sys.argv[1] if len(sys.argv) > 1 else
            os.path.join(os.path.dirname(os.path.abspath(__file__)), "hier.S"))
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write(generate())
    print(f"wrote {path}")
