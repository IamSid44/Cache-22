#!/usr/bin/env python3
"""Generate sw/bench/code_walk.S.

    python sw/bench/gen_code_walk.py
"""

import os

BODY = 640          # instructions in the straight-line body (80 cache lines)
PASSES = 30
MASK64 = (1 << 64) - 1


def body():
    """(assembly text, function applying it to the accumulator)."""
    lines, ops = [], []
    for i in range(BODY):
        if i % 2 == 0:
            k = (i * 37) % 1000 + 1
            lines.append(f"    addi a0, a0, {k}")
            ops.append(("add", k))
        else:
            k = (i * 53) % 2000 + 1
            if k > 2047:
                k = 2047
            lines.append(f"    xori a0, a0, {k}")
            ops.append(("xor", k))
    return lines, ops


def expected(ops):
    """Mirror of the program, independent of the simulator."""
    a0 = 0
    for _ in range(PASSES):
        for kind, k in ops:
            a0 = (a0 + k) & MASK64 if kind == "add" else a0 ^ k
    return a0


def main():
    lines, ops = body()
    value = expected(ops)
    text = f"""# code_walk.S - straight-line code much larger than the instruction cache.
# GENERATED by sw/bench/gen_code_walk.py; edit that script, not this file.
# Shows: the instruction cache and next-line prefetching of instructions.
.equ HALT, 0x10000008
.equ PASSES, {PASSES}

    li   a0, 0
    li   s1, PASSES
pass_top:
{chr(10).join(lines)}
    addi s1, s1, -1
    bnez s1, pass_top

    li   gp, 1
    li   t5, {value}
    bne  a0, t5, fail

pass:
    li   t6, HALT
    sd   x0, 0(t6)
pass_loop:
    j    pass_loop
fail:
    li   t6, HALT
    sd   gp, 0(t6)
fail_loop:
    j    fail_loop
"""
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "code_walk.S")
    with open(path, "w", encoding="ascii", newline="\n") as handle:
        handle.write(text)
    print(f"wrote {path}: {BODY} instructions x {PASSES} passes, expected a0 = {value}")


if __name__ == "__main__":
    main()
